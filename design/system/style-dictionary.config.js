// Style Dictionary 5: builds CSS variables, a Swift token file for the tests and a flat JSON (for the Storybook pages)
// from tokens.json. Values live only in the token file; this file only formats them.
const MODES = ['dark', 'light'];

const val = (t) => (t.$value !== undefined ? t.$value : t.value);
const typeOf = (t) => t.$type ?? t.type;
const modeOf = (t) => (t.path[0] === 'color' && MODES.includes(t.path[1]) ? t.path[1] : null);
const plainPath = (t) => (modeOf(t) ? [t.path[0], ...t.path.slice(2)] : t.path);
const cssName = (t) => '--tp-' + plainPath(t).join('-').replace(/_/g, '-');

function rgba(c) {
  const [r, g, b] = c.components.map((x) => Math.round(x * 255));
  const a = c.alpha === undefined ? 1 : c.alpha;
  return { r, g, b, a };
}
function cssColor(c) {
  const { r, g, b, a } = rgba(c);
  return a === 1 ? c.hex : `rgba(${r}, ${g}, ${b}, ${a})`;
}
const px = (d) => `${d.value}${d.unit}`;
function cssValue(t) {
  const v = val(t);
  switch (typeOf(t)) {
    case 'color': return cssColor(v);
    case 'dimension': return px(v);
    case 'fontFamily': return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
    default: return String(v);
  }
}

// ---------------------------------------------------------------- CSS
const cssFormat = ({ dictionary }) => {
  const shared = [], byMode = { dark: [], light: [] };
  for (const t of dictionary.allTokens) {
    const line = `  ${cssName(t)}: ${cssValue(t)};`;
    const m = modeOf(t);
    (m ? byMode[m] : shared).push(line);
  }
  // the cell: one character of SF Mono 12, so a run of N cells is N ch wide
  shared.push('  --tp-cell: 1ch;');
  return `/* Generated by Style Dictionary from design/system/tokens.json. Do not edit. */
:root {
${shared.join('\n')}
}
:root, [data-theme="dark"] {
  color-scheme: dark;
${byMode.dark.join('\n')}
}
[data-theme="light"] {
  color-scheme: light;
${byMode.light.join('\n')}
}
`;
};

// ---------------------------------------------------------------- Swift
// The Swift names are the names in Tokens.swift: kebab to camel, and the hue- group prefix dropped.
const camel = (s) => s.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
const swiftColorName = (t) => camel(t.path.slice(2).join('-').replace(/^hue-/, ''));
const hex = (c) => '0x' + c.hex.slice(1).toLowerCase();
const swiftRGBA = (c) => ((c.alpha ?? 1) === 1 ? `RGBA(hex: ${hex(c)})` : `RGBA(hex: ${hex(c)}, alpha: ${c.alpha})`);
const swiftNum = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);

const swiftFormat = ({ dictionary }) => {
  const colors = { dark: [], light: [] }, sizes = [], cells = [], font = [], chrome = [];
  for (const t of dictionary.allTokens) {
    const ty = typeOf(t), m = modeOf(t), d = t.$description ?? t.comment ?? '';
    if (ty === 'color' && m) colors[m].push([swiftColorName(t), swiftRGBA(val(t)), d]);
    else if (t.path[0] === 'size') sizes.push([camel(t.path.slice(1).join('-')), val(t).value, d]);
    else if (t.path[0] === 'cells') cells.push([camel(t.path.slice(1).join('-')), val(t), d]);
    else if (t.path[0] === 'font') font.push([t.path.slice(1).join('-'), t, d]);
    else if (t.path[0] === 'chrome') chrome.push([camel(t.path.slice(1).join('-')), ty === 'color' ? swiftRGBA(val(t)) : ty === 'dimension' ? `${val(t).value} as Double` : `${val(t)} as Double`, d]);
  }
  const doc = (d, ind) => (d ? `${ind}/// ${d}\n` : '');
  let s = `// SPDX-FileCopyrightText: 2026 tokenpanda
// SPDX-License-Identifier: MIT
// Generated by Style Dictionary from design/system/tokens.json. Do not edit: run npm run tokens in design/system.
// Compiled into the tests only; TokensSyncTests holds every value here against Sources/Text/Tokens.swift and the panel measures.
import Text

/// The design tokens as built from tokens.json.
enum DesignTokens {
`;
  for (const m of MODES) {
    s += `    /// The ${m} palette${m === 'light' ? ': the light partner of each dark token (Tokens.light), and tintLight, stageLight' : ': the token table of Tokens.swift'}.\n`;
    s += `    enum ${m === 'dark' ? 'Dark' : 'Light'} {\n`;
    for (const [k, v, d] of colors[m]) s += doc(d, '        ') + `        static let ${k} = ${v}\n`;
    s += '    }\n\n';
  }
  for (const m of MODES) {
    s += `    /// The ${m} palette by Tokens.swift name.\n    static let ${m}ByName: [String: RGBA] = [\n`;
    for (const [k] of colors[m]) s += `        "${k}": ${m === 'dark' ? 'Dark' : 'Light'}.${k},\n`;
    s += '    ]\n\n';
  }
  s += '    /// Panel measures in points.\n    enum Size {\n';
  for (const [k, v, d] of sizes) s += doc(d, '        ') + `        static let ${k}: Double = ${swiftNum(v)}\n`;
  s += '    }\n\n    /// Cell counts of the line grammar.\n    enum Cells {\n';
  for (const [k, v, d] of cells) s += doc(d, '        ') + `        static let ${k} = ${v}\n`;
  s += '    }\n\n    enum Font {\n';
  for (const [k, t, d] of font) {
    const v = val(t);
    const name = camel(k);
    if (typeOf(t) === 'fontFamily') s += doc(d, '        ') + `        static let ${name} = [${v.map((f) => `"${f}"`).join(', ')}]\n`;
    else if (typeOf(t) === 'dimension') s += doc(d, '        ') + `        static let ${name}: Double = ${v.value}\n`;
    else s += doc(d, '        ') + `        static let ${name} = ${v}\n`;
  }
  s += '    }\n\n    /// OS chrome around the app, for the stage only: the menu bar strip and the nudge banner.\n    enum Chrome {\n';
  for (const [k, v, d] of chrome) s += doc(d, '        ') + `        static let ${k} = ${v}\n`;
  s += '    }\n}\n';
  return s;
};

// ---------------------------------------------------------------- JSON for the Storybook pages
const jsonFormat = ({ dictionary }) => JSON.stringify(dictionary.allTokens.map((t) => ({
  name: cssName(t), path: t.path.join('.'), type: typeOf(t), mode: modeOf(t), css: cssValue(t),
  swift: typeOf(t) === 'color' && modeOf(t) ? swiftColorName(t) : null,
  value: val(t), description: t.$description ?? t.comment ?? '',
})), null, 2);

export default {
  source: ['tokens.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  hooks: {
    formats: { 'tp/css': cssFormat, 'tp/swift': swiftFormat, 'tp/json': jsonFormat },
  },
  platforms: {
    css: { buildPath: 'build/css/', transforms: ['name/kebab'], files: [{ destination: 'tokens.css', format: 'tp/css' }] },
    swift: { buildPath: '../../Tests/tokenpandaTests/Generated/', transforms: ['name/kebab'], files: [{ destination: 'DesignTokens.swift', format: 'tp/swift' }] },
    json: { buildPath: 'build/json/', transforms: ['name/kebab'], files: [{ destination: 'tokens.json', format: 'tp/json' }] },
  },
};
